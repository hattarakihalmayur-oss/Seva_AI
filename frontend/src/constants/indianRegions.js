/**
 * Get localized display name for an Indian state / territory
 * @param {string} stateKey - English state name (e.g., 'Karnataka')
 * @param {string} langCode - Language code ('kn', 'hi', etc.)
 * @returns {string} - Formatted regional name e.g. 'ಕರ್ನಾಟಕ (Karnataka)'
 */
export const getStateDisplayName = (stateKey, langCode = 'en') => {
  if (!stateKey || stateKey === 'All') return stateKey;
  const translation = STATE_TRANSLATIONS[stateKey]?.[langCode];
  if (!translation) return stateKey;
  if (langCode === 'en') return stateKey;
  return `${translation} (${stateKey})`;
};

